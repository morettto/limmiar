import { test, expect } from '@playwright/test'
import { abrirCarteira, registrarProfissionalNaInterface } from './fixtures/profissional-interface'

test('código cadastrado recupera paciente na API real e revoga os segredos antigos', async ({ page, request }) => {
  test.setTimeout(60000)
  const professional = await registrarProfissionalNaInterface(page, request)
  await abrirCarteira(page)
  const name = `Paciente sintético ${crypto.randomUUID()}`
  await page.locator('details.patient-add > summary').click()
  await page.getByLabel('Nome do paciente', { exact: true }).fill(name)
  await page.getByRole('button', { name: 'Adicionar paciente', exact: true }).click()
  await expect(page.getByRole('link', { name, exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Chave pessoal', { exact: true })).toBeVisible()
  await expect(page.getByText(name, { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Perdi minha chave pessoal', exact: true }).click()
  await page.getByLabel('Código de recuperação', { exact: true }).fill(professional.codigosRecuperacao[0]!)
  await page.getByRole('button', { name: 'Gerar nova chave', exact: true }).click()
  const key = await page.locator('.vault-secret').textContent()
  const codes = await page.locator('.vault-codes code').allTextContents()
  expect(key).not.toBe(professional.chavePessoal)
  expect(codes).toHaveLength(3)
  await page.getByLabel('Últimos 6 caracteres da chave pessoal', { exact: true }).fill(key!.slice(-6))
  await page.getByRole('checkbox').check()
  const recovered = page.waitForResponse(response => response.url().endsWith('/clinical-vault/recover') && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Concluir e abrir consultório', exact: true }).click()
  expect((await recovered).status()).toBe(204)
  await expect(page.getByRole('link', { name, exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Bloquear prontuários', exact: true }).click()
  await page.getByLabel('Chave pessoal', { exact: true }).fill(professional.chavePessoal)
  await page.getByRole('button', { name: 'Desbloquear prontuários', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Chave inválida')
  await page.getByRole('button', { name: 'Perdi minha chave pessoal', exact: true }).click()
  await page.getByLabel('Código de recuperação', { exact: true }).fill(professional.codigosRecuperacao[1]!)
  await page.getByRole('button', { name: 'Gerar nova chave', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Código inválido')
  await page.getByRole('button', { name: 'Voltar ao desbloqueio', exact: true }).click()
  await page.getByLabel('Chave pessoal', { exact: true }).fill(key!)
  await page.getByRole('button', { name: 'Desbloquear prontuários', exact: true }).click()
  await expect(page.getByRole('link', { name, exact: true })).toBeVisible()
})
