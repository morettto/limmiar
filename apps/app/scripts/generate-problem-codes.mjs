import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = fileURLToPath(new URL('../../..', import.meta.url))
const apiSourceRoot = join(repoRoot, 'apps', 'api', 'src', 'Api')
const outputPath = join(repoRoot, 'apps', 'app', 'src', 'shared', 'api', 'problem-codes.ts')

const CONST_PATTERN = /public\s+const\s+string\s+\w+\s*=\s*"([^"]+)"\s*;/g

function findProblemCodeFiles(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const entryPath = join(directory, entry.name)
    if (entry.isDirectory()) {
      return entry.name === 'bin' || entry.name === 'obj' ? [] : findProblemCodeFiles(entryPath)
    }
    return entry.name.endsWith('ProblemCodes.cs') ? [entryPath] : []
  })
}

const sourceFiles = findProblemCodeFiles(apiSourceRoot).sort()

if (sourceFiles.length === 0) {
  throw new Error(
    `No *ProblemCodes.cs found under ${relative(repoRoot, apiSourceRoot)}. ` +
      'If the API layout moved, update apiSourceRoot in this script.',
  )
}

const codes = new Map()

for (const sourceFile of sourceFiles) {
  const contents = readFileSync(sourceFile, 'utf8')
  for (const [, code] of contents.matchAll(CONST_PATTERN)) {
    const previous = codes.get(code)
    if (previous !== undefined) {
      throw new Error(
        `Problem code "${code}" is declared twice: ${relative(repoRoot, previous)} and ${relative(repoRoot, sourceFile)}.`,
      )
    }
    codes.set(code, sourceFile)
  }
}

if (codes.size === 0) {
  throw new Error(
    `Found ${sourceFiles.length} *ProblemCodes.cs file(s) but no 'public const string' declarations. ` +
      'The C# declaration shape changed; update CONST_PATTERN in this script.',
  )
}

const sortedCodes = [...codes.keys()].sort()

const generated = `// Generated by apps/app/scripts/generate-problem-codes.mjs from apps/api/src/Api/**/*ProblemCodes.cs — do not edit by hand.
export const problemCodes = [
${sortedCodes.map((code) => `  '${code}',`).join('\n')}
] as const

export type ProblemCode = (typeof problemCodes)[number]
`

writeFileSync(outputPath, generated, 'utf8')

process.stdout.write(`${sortedCodes.length} problem codes from ${sourceFiles.length} file(s) -> ${relative(repoRoot, outputPath)}\n`)
